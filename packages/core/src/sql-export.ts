export interface SqlExportReportEntry {
  readonly code: string;
  readonly status: Exclude<ConversionStatus, "EXACT">;
  readonly message: string;
  readonly occurrences: SqlExportOccurrence[];
}

export interface SqlExportReport {
  readonly reportVersion: typeof SQL_EXPORT_REPORT_VERSION;
  readonly exportSemanticsVersion: typeof SQL_EXPORT_SEMANTICS_VERSION;
  readonly sourceFilepath: string;
  readonly sourceHash: string;
  readonly parserInputHash: string;
  readonly primaryDialect: PrimaryDialect;
  readonly targetDialect: PrimaryDialect;
  readonly parserVersions: {
    readonly dbmlCore: typeof DBML_PARSER_VERSION;
    readonly dbmlParse: typeof DBML_PARSER_VERSION;
  };
  readonly schemaSemanticsVersion: typeof SCHEMA_SEMANTICS_VERSION;
  readonly ddlKind: "EMPTY_SCHEMA_CREATE";
  readonly overallStatus: ConversionStatus;
  readonly acknowledgementRequired: boolean;
  readonly generatedSqlHash: string | null;
  readonly containsDataStatements: boolean;
  readonly entries: SqlExportReportEntry[];
  readonly diagnostics: Diagnostic[];
  readonly semanticVerification: SqlExportSemanticVerification;
}

export type SqlExportConversionResult =
  | {
      readonly ok: true;
      readonly report: SqlExportReport;
      readonly candidate: {
        readonly sql: string;
        readonly sqlHash: string;
      };
    }
  | {
      readonly ok: false;
      readonly report: SqlExportReport;
      readonly candidate: null;
    };

