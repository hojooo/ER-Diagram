async function installWorkspaceApi(
  page: Page,
  state: ReturnType<typeof projectState> = projectState(),
  options: { readonly draftWrite?: "CONFLICT" } = {},
) {
  const layouts = createControlledLayoutApi(PROJECT_ID);
  await page.route("**/api/v1/projects**", async (route) => {
    const request = route.request();
    const pathname = new URL(request.url()).pathname;
    const method = request.method();
    const command = request.postDataJSON() as Record<string, unknown> | null;
    const commandId = typeof command?.commandId === "string" ? command.commandId : undefined;
    const headers = {
      "content-type": "application/json",
      "x-correlation-id": "123e4567-e89b-42d3-a456-426614174000",
      ...(commandId ? { "x-command-id": commandId } : {}),
    };
    if (await layouts.fulfillIfMatched({ route, pathname, method, command, headers })) return;
    if (method === "GET" && pathname === "/api/v1/projects") {
      await route.fulfill({
        status: 200,
        headers,
        body: JSON.stringify({ projects: [projectSummary(state)] }),
      });
      return;
    }
    if (method === "GET" && pathname === `/api/v1/projects/${PROJECT_ID}`) {
      await route.fulfill({ status: 200, headers, body: JSON.stringify({ state }) });
      return;
    }
    if (method === "GET" && pathname === `/api/v1/projects/${PROJECT_ID}/revisions`) {
      const { source: _source, ...revisionSummary } = state.currentRevision;
      await route.fulfill({
        status: 200,
        headers,
        body: JSON.stringify({ revisions: [revisionSummary] }),
      });
      return;
    }
    if (method === "PUT" && pathname === `/api/v1/projects/${PROJECT_ID}/draft`) {
      if (options.draftWrite === "CONFLICT") {
        await route.fulfill({
          status: 409,
          headers,
          body: JSON.stringify({
            code: "PROJECT_SCHEMA_REVISION_CONFLICT",
            message: "The schema revision is stale.",
            correlationId: headers["x-correlation-id"],
            currentRevisionNo: state.project.schemaRevisionNo + 1,
          }),
        });
        return;
      }
      await route.fulfill({
        status: 500,
        headers,
        body: JSON.stringify({
          code: "INTERNAL_SERVER_ERROR",
          message: "The draft could not be saved.",
          correlationId: headers["x-correlation-id"],
        }),
      });
      return;
    }
    await route.fulfill({
      status: 404,
      headers,
      body: JSON.stringify({
        code: "PROJECT_NOT_FOUND",
        message: "Project not found.",
        correlationId: headers["x-correlation-id"],
      }),
    });
  });
  return { layouts };
}

async function replaceEditorSource(page: Page, source: string): Promise<void> {
  const modifier = process.platform === "darwin" ? "Meta" : "Control";
  const editor = page.getByRole("textbox", { name: "DBML source editor" });
  await editor.focus();
  await editor.press(`${modifier}+a`);
  await editor.evaluate((element, nextSource) => {
    const clipboardData = new DataTransfer();
    clipboardData.setData("text/plain", nextSource);
    element.dispatchEvent(
      new ClipboardEvent("paste", { bubbles: true, cancelable: true, clipboardData }),
    );
  }, source);
}

