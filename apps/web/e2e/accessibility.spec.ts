test("startup loading and failure states expose a single accessible main flow", async ({
  page,
}) => {
  let releaseFirstRequest: (() => void) | undefined;
  let runtimeRequests = 0;
  await page.route("**/api/v1/runtime-config", async (route) => {
    runtimeRequests += 1;
    if (runtimeRequests > 1) {
      await route.fallback();
      return;
    }
    await new Promise<void>((resolve) => {
      releaseFirstRequest = resolve;
    });
    await route.fulfill({
      status: 500,
      contentType: "application/json",
      body: JSON.stringify({ code: "STARTUP_FAILURE" }),
    });
  });
  await installEmptyProjectList(page);
  await page.goto("/");

  await expect(page.getByRole("heading", { name: "Starting workspace" })).toBeVisible();
  await assertNoWcagViolations(page, "runtime configuration loading");
  releaseFirstRequest?.();
  await expect(
    page.getByRole("heading", { name: "Runtime configuration unavailable" }),
  ).toBeVisible();
  await assertNoWcagViolations(page, "runtime configuration error");

  await page.getByRole("button", { name: "Retry" }).click();
  await expect(page.getByRole("heading", { name: "Projects", exact: true })).toBeVisible();
});

